    parser.add_argument("--flickr_mlp_dir", default="./checkpoints/flickr30k_mlp")
    parser.add_argument("--flickr_mlp_prefix", default="flickr30k_mlp")
    parser.add_argument("--flickr_transformer_dir", default="./checkpoints/flickr30k_transformer_frozen")
    parser.add_argument("--flickr_transformer_prefix", default="flickr30k_transformer_frozen")
