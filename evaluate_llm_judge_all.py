    parser.add_argument("--mscoco_transformer_prefix", default="mscoco_transformer_frozen")
    parser.add_argument("--mscoco_finetune_dir", default="./checkpoints/mscoco_transformer_finetune")
    parser.add_argument("--mscoco_finetune_prefix", default="mscoco_transformer_finetune")
